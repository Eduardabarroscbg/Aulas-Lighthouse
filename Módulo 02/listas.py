# Módulo 2 - Listas
# Serve pra guardar vários valores numa variável só, sem precisar ficar
# criando nome_1, nome_2, nome_3... Cada item tem um índice, que começa em zero.

alunos = ["Maria", "Ana", "José", "Catarina"]

print(alunos[0])  # Maria
print(alunos[1])  # Ana

for aluno in alunos:
    print(aluno)

# Tamanho da lista
print(len(alunos))  # 4
